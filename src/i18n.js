/* Traduit une clé ; les entrées fonctions reçoivent les arguments donnés.
   Nommée tr et non t : dans le rendu des cartes, `t` désigne déjà la carte
   en cours de traitement, et l'appel se ferait sur elle. */
function tr(cle, ...args) {
  const dict = I18N[prefs.lang] || I18N.fr;
  const valeur = dict[cle] !== undefined ? dict[cle] : I18N.fr[cle];
  return typeof valeur === 'function' ? valeur(...args) : valeur;
}
